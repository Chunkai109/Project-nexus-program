// Vendors MediaPipe Tasks Vision assets into public/ so pose detection can
// run entirely from same-origin files instead of depending on a
// third-party CDN or Google's model-hosting servers at request time:
//  1. The WASM runtime, copied from node_modules (already downloaded by
//     npm, no network fetch needed here).
//  2. The pose landmarker model file itself (~5.5MB), downloaded once here.
// (2) matters even beyond "restrictive networks blocking third-party
// CDNs" — this project's own ESP32 hub creates an isolated WiFi access
// point with NO internet route at all once you join it (see
// firmware/README.md), and the model file was previously always fetched
// live from storage.googleapis.com regardless of which WASM path was used,
// so pose detection silently failed for anyone testing with the real
// hardware connected and their normal WiFi/internet disconnected. Runs
// automatically after `npm install` (see package.json). Not committed to
// git — regenerated by every install, same as node_modules.
import { cpSync, existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const publicMediapipeDir = join(__dirname, '..', 'public', 'mediapipe')

// 1. WASM runtime
const wasmSrc = join(__dirname, '..', 'node_modules', '@mediapipe', 'tasks-vision', 'wasm')
const wasmDest = join(publicMediapipeDir, 'wasm')
if (existsSync(wasmSrc)) {
  mkdirSync(wasmDest, { recursive: true })
  cpSync(wasmSrc, wasmDest, { recursive: true })
  console.log('[vendor-mediapipe] copied WASM runtime into public/mediapipe/wasm')
} else {
  console.warn('[vendor-mediapipe] WASM source not found in node_modules, skipping:', wasmSrc)
}

// 2. Pose landmarker model file — needs a real network fetch (this file
// isn't in node_modules), so it's skipped, not fatal, if offline right now;
// the app falls back to fetching it live from Google at runtime in that
// case (see usePoseLandmarker.ts's MODEL_CONFIGS), which then needs real
// internet access to work.
const MODEL_URL =
  'https://storage.googleapis.com/mediapipe-models/pose_landmarker/pose_landmarker_lite/float16/1/pose_landmarker_lite.task'
const modelDest = join(publicMediapipeDir, 'models', 'pose_landmarker_lite.task')

if (existsSync(modelDest)) {
  console.log('[vendor-mediapipe] pose landmarker model already present, skipping download')
} else {
  try {
    const res = await fetch(MODEL_URL)
    if (!res.ok) throw new Error(`HTTP ${res.status}`)
    const bytes = Buffer.from(await res.arrayBuffer())
    mkdirSync(dirname(modelDest), { recursive: true })
    writeFileSync(modelDest, bytes)
    console.log(`[vendor-mediapipe] downloaded pose landmarker model into public/mediapipe/models (${bytes.length} bytes)`)
  } catch (err) {
    console.warn('[vendor-mediapipe] could not download the pose landmarker model (offline install?):', err.message)
    console.warn(
      '[vendor-mediapipe] the app will fetch it live from Google at runtime instead — that needs real internet ' +
        "access, which the ESP32 hub's own isolated WiFi network does NOT provide once you join it. Re-run " +
        '`npm install` while online to fix this permanently.',
    )
  }
}
